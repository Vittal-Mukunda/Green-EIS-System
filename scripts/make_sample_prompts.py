"""Write docs/sample_prompts.md: complete prompts for the owner to review before `gauge freeze`.

Section A is the C1 prompt on the REAL candidate companies (provisional: the final sample is not
selected yet, and FY2022-23 / FY2023-24 are not loaded, so no real C2 can be built). Section B is
the C2 prompt on SYNTHETIC data, so the format of the added context can be reviewed now. Run:

    python scripts/make_sample_prompts.py
"""

from __future__ import annotations

import sys
from pathlib import Path

from sqlalchemy.engine import make_url

from gauge.config import load_indicators, load_study, project_root
from gauge.db.session import make_engine, session_scope
from gauge.pipeline import DRY_CONFIG, run_all_dry
from gauge.render.runs import prepare_render
from gauge.render.sample import sample_section

HEADER = """\
# Sample prompts

Generated by `scripts/make_sample_prompts.py`. Do not edit by hand: change the templates in
`registry/prompts/` (or the renderer) and regenerate. Nothing is frozen yet.

Each prompt below is shown exactly as a Cursor model would receive it: the instructions (system
part), then a line `---`, then the evidence (user part). The API baseline receives the same two
parts as a system message and a user message. In a real run the order of the companies is shuffled
per run (and logged); here they are in code order.

* **A** is the C1 prompt on the real candidate companies. It is *provisional*: the final sample is
  not selected, the masked codes will be renumbered, and the cut-points are computed from the 20
  candidates, so every number will change once the FY2023-24 filings are loaded and `gauge select`
  has run.
* **B** is the C2 prompt on *synthetic* data (invented numbers, 2 made-up sectors). A real C2
  cannot be built before the FY2022-23 and FY2023-24 data exist. The only difference between C1
  and C2 is the context table that C2 adds after each company's block (the C1 block is repeated
  unchanged above it) and one sentence in the introduction. The synthetic data deliberately contain
  one gap, which shows how a missing value is printed (`not reported`).
"""

REVIEW = """\
## What to check, and the decisions to confirm

Please read the instructions in A once, slowly, and look at one company block in each condition.
Then confirm or change each point (they are my choices, not the spec's):

1. **The rule is applied to the printed numbers.** KPIs and cut-points are shown to 4 significant
   figures and the T2 class is computed from those printed values, so a reader can reproduce the
   class from the prompt alone (a test checks this). A value exactly equal to a cut-point takes the
   better of the two tertiles; the prompt says so.
2. **No worked example.** The prompt lists the JSON fields but gives no filled-in example, so
   there is nothing for a model to copy or be anchored by.
3. **`t3_rating` is only anchored at the ends** (1 = very weak, 5 = very strong environmental
   performance). I did not say "relative to the sector" or "in absolute terms": it is the model's
   own assessment (spec 4.4), and how models read it is part of what is measured. Say if you want a
   definition added; that would be a new prompt version.
4. **`top_drivers` must come from a printed list** of 14 names (9 reported indicators and 5 KPIs,
   including "Revenue from operations"), so the grounding check can match them exactly.
5. **KPI definitions are printed** in words, with the unit. Water intensity uses water
   *consumption* (your decision on V-05).
6. **C2 context** shows all 5 KPIs for the 3 years and the sector P25 / median / P75 for the
   analysis year. The 2-year % change is not printed (it is derivable from the table).
7. **Cut-point provenance is stated**, including how many companies they come from ("the 5 companies
   of this sector in the study sample"). Keep that sentence, or drop it?
8. **Assurance status.** `assured` means all four environmental disclosure groups carry reasonable
   or limited assurance in the XBRL. The FY2024-25 figures come from the *comparative* column of the
   FY2025-26 filings, which says nothing about that year's assurance, so section A prints "not
   stated". Downloading the as-filed FY2024-25 filings (an optional extra 20 files) would fill it in
   and would also replace the comparative figures by the as-filed ones.
9. **Nothing about the study leaks**: no mention of conditions, of T2/T3 as a design, of other
   models, or of what is being measured. The names `t2_class` and `t3_rating` are only JSON keys.
10. **A waste recovery rate above 100% appears** (for example CEM-03 at 103.8%) because the filer
    reported more recovered than generated waste (V-27). It is kept as filed. The waste KPI is not
    one of the three core KPIs, so it changes no T2 class and no T3 signal. Keep it, or drop the
    waste KPI from the prompts?

When you are happy: `gauge select` (after the FY2023-24 files are loaded), `gauge benchmarks`,
`gauge build-rules`, `gauge render --sample`, and then `gauge freeze`. The runner refuses to start
if any frozen file or any rendered prompt later differs from the manifest.
"""


def main() -> int:
    root = project_root()
    out = root / "docs" / "sample_prompts.md"
    parts = [HEADER]

    real = load_study("config/study.yaml", root=root)
    indicators = load_indicators(real)
    url = make_url(real.database_url())
    if url.database and Path(url.database).is_file():
        engine = make_engine(real.database_url())
        try:
            with session_scope(engine) as session:
                ctx = prepare_render(session, real, indicators, provisional=True, with_trend=False)
                parts.append(
                    sample_section(
                        real, indicators, ctx, ["C1"], heading="A. C1 on real candidate data"
                    )
                )
        finally:
            engine.dispose()
    else:
        parts.append("## A. C1 on real candidate data\n\n*No real database yet.*\n")

    run_all_dry(DRY_CONFIG, root=root)  # deterministic; rebuilds dry/ from scratch
    dry = load_study(DRY_CONFIG, root=root)
    engine = make_engine(dry.database_url())
    try:
        with session_scope(engine) as session:
            ctx = prepare_render(session, dry, load_indicators(dry))
            parts.append(
                sample_section(
                    dry, load_indicators(dry), ctx, ["C2"], heading="B. C2 on synthetic data"
                )
            )
    finally:
        engine.dispose()

    parts.append(REVIEW)
    out.write_bytes(("\n".join(parts)).encode("utf-8"))
    print(f"wrote {out} ({out.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
