"""Export the schema as DDL (docs/schema.sql, docs/schema_postgres.sql)."""

from __future__ import annotations

from pathlib import Path

from sqlalchemy.dialects import postgresql, sqlite
from sqlalchemy.engine import Dialect
from sqlalchemy.schema import CreateIndex, CreateTable

from gauge.db import models  # noqa: F401
from gauge.db.base import Base

_DIALECTS: dict[str, Dialect] = {"sqlite": sqlite.dialect(), "postgresql": postgresql.dialect()}

HEADER = """-- GENERATED by `gauge init-db --ddl-only` (src/gauge/db/ddl.py). Do not edit by hand.
-- Dialect: {dialect}. Source of truth: src/gauge/db/models.py.
"""


def generate_ddl(dialect: str = "sqlite") -> str:
    """Deterministic CREATE TABLE / CREATE INDEX script for the given dialect."""
    dia = _DIALECTS[dialect]
    parts = [HEADER.format(dialect=dialect)]
    for table in Base.metadata.sorted_tables:
        parts.append(str(CreateTable(table).compile(dialect=dia)).strip() + ";\n")
        for index in sorted(table.indexes, key=lambda i: i.name or ""):
            parts.append(str(CreateIndex(index).compile(dialect=dia)).strip() + ";\n")
    return "\n".join(parts)


def write_ddl_files(docs_dir: Path) -> list[Path]:
    """Write docs/schema.sql (SQLite, what we run) and docs/schema_postgres.sql (portability)."""
    targets = {"sqlite": docs_dir / "schema.sql", "postgresql": docs_dir / "schema_postgres.sql"}
    docs_dir.mkdir(parents=True, exist_ok=True)
    for dialect, path in targets.items():
        path.write_text(generate_ddl(dialect), encoding="utf-8", newline="\n")
    return list(targets.values())
