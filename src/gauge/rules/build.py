"""Build the T2 and T3-update rule files from the benchmarks, and load them back, validated.

`registry/rules/t2_v1.yaml` holds the rule's structure AND each sector's numeric cut-points (at the
displayed precision), so the file alone is enough to classify any company from its displayed KPIs.
`registry/rules/t3_update_v1.yaml` holds the update rule; models never see it.
"""

from __future__ import annotations

from decimal import Decimal
from pathlib import Path

import yaml

from gauge.config import IndicatorsConfig, StudyConfig
from gauge.render.evidence import Evidence
from gauge.rules.rounding import plain
from gauge.rules.t2 import CutPoints, T2Metric, T2Rule
from gauge.rules.t3 import BenchmarkSpec, T3Rule, TrendSpec

T2_RULE_ID = "t2_v1"
T3_RULE_ID = "t3_update_v1"

SCORES = {"best": 2, "middle": 1, "worst": 0}
CLASSES = {"Leader": (5, 6), "Average": (2, 4), "Laggard": (0, 1)}
TIE_RULE = "a value exactly equal to a cut-point belongs to the better of the two tertiles"
TREND_THRESHOLD_PCT = Decimal(5)
MIN_METRICS = 2

T2_HEADER = """\
# T2 rule (spec 4.5), FROZEN once `gauge freeze` has run. Generated by `gauge build-rules`.
# Each core KPI is scored against its sector's tertile cut-points: best third 2, middle 1, worst 0.
# Total 5-6 Leader, 2-4 Average, 0-1 Laggard. Cut-points are the 1/3 and 2/3 quantiles of the
# study's own sector sample for the analysis year, shown rounded to `display_significant_figures`;
# the rule is applied to the DISPLAYED (rounded) KPI values. Do not edit by hand.
"""

T3_HEADER = """\
# T3 update rule (spec 4.6), FROZEN once `gauge freeze` has run. Generated by `gauge build-rules`.
# Used only by the evaluator to label each C1 -> C2 rating change; it is never shown to a model.
# Trend and benchmark signals are computed from the same displayed numbers that appear in C2.
"""


class RuleFileError(ValueError):
    """A rule file is missing, unreadable or invalid."""


def _core_metrics(indicators: IndicatorsConfig) -> list[T2Metric]:
    return [T2Metric(kpi=k.code, better=k.better) for k in indicators.core_kpis]


def build_t2_rule(evidence: Evidence, cfg: StudyConfig, indicators: IndicatorsConfig) -> T2Rule:
    metrics = _core_metrics(indicators)
    cut_points: dict[str, dict[str, CutPoints]] = {}
    for sector in cfg.study.sectors:
        bench = evidence.sectors.get(sector.name)
        if bench is None:
            continue  # a sector without companies in the evidence set has no cut-points
        cut_points[sector.name] = {
            m.kpi: CutPoints(
                p33=bench.stats[m.kpi]["p33"], p67=bench.stats[m.kpi]["p67"], n=bench.n
            )
            for m in metrics
        }
    expected = {s.name for s in cfg.study.sectors}
    if set(cut_points) != expected:
        raise RuleFileError(f"no cut-points for sector(s) {sorted(expected - set(cut_points))}")
    return T2Rule(
        rule_id=T2_RULE_ID,
        analysis_fy=evidence.analysis_fy,
        display_significant_figures=evidence.figures,
        metrics=metrics,
        scores=SCORES,
        classes=CLASSES,
        tie_rule=TIE_RULE,
        cut_points=cut_points,
    )


def build_t3_rule(evidence: Evidence, indicators: IndicatorsConfig) -> T3Rule:
    return T3Rule(
        rule_id=T3_RULE_ID,
        core_metrics=_core_metrics(indicators),
        trend=TrendSpec(
            from_fy=evidence.trend_fys[0],
            to_fy=evidence.trend_fys[-1],
            threshold_pct=TREND_THRESHOLD_PCT,
            min_metrics=MIN_METRICS,
        ),
        benchmark=BenchmarkSpec(
            fy=evidence.analysis_fy, against="sector_median", min_metrics=MIN_METRICS
        ),
    )


# ---- (de)serialisation -------------------------------------------------------------------------
def _plain_data(value):
    """Decimals become plain strings (never floats, never exponents), tuples become lists."""
    if isinstance(value, Decimal):
        return plain(value)
    if isinstance(value, dict):
        return {k: _plain_data(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_plain_data(v) for v in value]
    return value


def rule_to_yaml(rule: T2Rule | T3Rule) -> str:
    header = T2_HEADER if isinstance(rule, T2Rule) else T3_HEADER
    body = yaml.safe_dump(
        _plain_data(rule.model_dump(mode="python")),
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
    )
    return header + "\n" + body


def write_rule(rule: T2Rule | T3Rule, path: Path) -> str:
    """Write the rule file; returns its text. Always UTF-8 with LF newlines (stable SHA-256)."""
    text = rule_to_yaml(rule)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
    return text


def _read(path: Path) -> dict:
    if not path.is_file():
        raise RuleFileError(f"rule file not found: {path} (run `gauge build-rules`)")
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise RuleFileError(f"{path} must contain a YAML mapping")
    return data


def load_t2_rule(path: Path) -> T2Rule:
    try:
        return T2Rule(**_read(path))
    except ValueError as exc:
        raise RuleFileError(f"invalid T2 rule {path}: {exc}") from exc


def load_t3_rule(path: Path) -> T3Rule:
    try:
        return T3Rule(**_read(path))
    except ValueError as exc:
        raise RuleFileError(f"invalid T3 rule {path}: {exc}") from exc


def rules_dir(cfg: StudyConfig) -> Path:
    return cfg.path(cfg.paths.rules_dir)


def t2_path(cfg: StudyConfig) -> Path:
    return rules_dir(cfg) / f"{T2_RULE_ID}.yaml"


def t3_path(cfg: StudyConfig) -> Path:
    return rules_dir(cfg) / f"{T3_RULE_ID}.yaml"


def check_rule_matches_evidence(rule: T2Rule, evidence: Evidence) -> list[str]:
    """Problems if the rule file's cut-points differ from the benchmarks behind the evidence.

    A mismatch means the rule is stale (data or sample changed after `build-rules`); the prompt
    would then print one set of cut-points while the evidence says another.
    """
    problems = []
    if rule.analysis_fy != evidence.analysis_fy:
        problems.append(f"rule is for {rule.analysis_fy}, evidence for {evidence.analysis_fy}")
    if rule.display_significant_figures != evidence.figures:
        problems.append("rule and evidence use different display precision")
    for sector, per_kpi in rule.cut_points.items():
        bench = evidence.sectors.get(sector)
        if bench is None:
            continue
        for kpi, cuts in per_kpi.items():
            stats = bench.stats[kpi]
            if (cuts.p33, cuts.p67, cuts.n) != (stats["p33"], stats["p67"], bench.n):
                problems.append(
                    f"{sector} {kpi}: rule has {plain(cuts.p33)}/{plain(cuts.p67)} (n={cuts.n}), "
                    f"benchmarks give {plain(stats['p33'])}/{plain(stats['p67'])} (n={bench.n})"
                )
    return problems
